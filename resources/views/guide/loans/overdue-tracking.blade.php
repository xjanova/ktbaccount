@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หน้านี้จะแนะนำวิธีติดตามหนี้ค้างชำระ ระบบจะช่วยแจ้งเตือนอัตโนมัติเมื่อสมาชิกค้างจ่าย
        เพื่อให้ติดตามทวงถามได้ทันเวลา ลดความเสี่ยงหนี้สูญ
    </p>

    <x-guide-step :number="1" title="ดูกล่องแจ้งเตือนบนหน้าหลัก (Dashboard)">
        <p>เมื่อเข้าระบบ หน้าแรก (Dashboard) จะมี <strong>กล่องแจ้งเตือนสีแดง</strong> แสดงขึ้นมา ถ้ามีสินเชื่อเลยกำหนดชำระ</p>
        <p>ข้อมูลในกล่องแจ้งเตือน:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>จำนวนสัญญาที่เลยกำหนด</strong> - เช่น "3 สัญญา" หมายถึงมี 3 สัญญาที่มีงวดค้างชำระ</li>
            <li><strong>ยอดเงินค้างชำระรวม</strong> - จำนวนเงินทั้งหมดที่ยังไม่ได้เก็บ</li>
        </ul>
        <p>คลิกที่กล่องแจ้งเตือนนี้ ระบบจะพาไปหน้ารายการสินเชื่อที่เลยกำหนดโดยตรง</p>
        <x-guide-tip type="info">
            ถ้าไม่เห็นกล่องสีแดง แสดงว่าขณะนี้ไม่มีสินเชื่อเลยกำหนดชำระ ไม่ต้องกังวล
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="2" title="เข้าเมนูสินเชื่อ แล้วกรองสถานะ &quot;เลยกำหนดชำระ&quot;">
        <p>อีกวิธีคือเข้าเมนู <strong>"สินเชื่อ"</strong> ในแถบด้านซ้ายมือ</p>
        <p>ที่ด้านบนของตาราง จะมี <strong>ตัวกรองสถานะ</strong> ให้เลือก กดที่ <strong>"เลยกำหนดชำระ"</strong> หรือ <strong>"ค้างชำระ"</strong></p>
        <p>ระบบจะแสดงเฉพาะสัญญาที่มีงวดเลยกำหนด เรียงจากค้างนานสุดไว้บนสุด</p>
        <x-guide-tip type="tip">
            ควรเข้ามาตรวจสอบหน้านี้ <strong>อย่างน้อยสัปดาห์ละ 1 ครั้ง</strong> เพื่อติดตามหนี้ค้างชำระได้ทันเวลา
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="3" title="ดูรายการสัญญาที่เลยกำหนด">
        <p>ตารางจะแสดงข้อมูลสัญญาที่เลยกำหนดชำระ แต่ละแถวมีรายละเอียดดังนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>ชื่อสมาชิก</strong> - ชื่อ-นามสกุลของผู้กู้</li>
            <li><strong>รหัสสัญญา</strong> - เลขอ้างอิงสัญญา</li>
            <li><strong>ยอดค้างชำระ</strong> - จำนวนเงินที่ยังไม่ได้จ่าย (เงินต้น + ดอกเบี้ย รวมกัน)</li>
            <li><strong>จำนวนวันที่เลยกำหนด</strong> - นับจากวันครบกำหนดจนถึงวันนี้ เช่น "15 วัน" หมายถึงเลยกำหนดมาแล้ว 15 วัน</li>
            <li><strong>จำนวนงวดที่ค้าง</strong> - เช่น "2 งวด" หมายถึงค้างจ่าย 2 งวดติดต่อกัน</li>
        </ul>
        <x-guide-tip type="warning">
            สัญญาที่แสดงสีแดงเข้มหรืออยู่ด้านบนสุดคือสัญญาที่ค้างนานที่สุด ควรติดตามก่อนเป็นอันดับแรก
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="4" title="ระบบแจ้งเตือน LINE อัตโนมัติ">
        <p>ระบบจะส่งข้อความแจ้งเตือนสมาชิกผ่าน <strong>LINE OA ของกองทุน</strong> อัตโนมัติตามกำหนดดังนี้:</p>

        <p class="mt-4 font-semibold">ก่อนครบกำหนดชำระ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>📢 <strong>7 วันก่อนครบกำหนด</strong> - แจ้งเตือนล่วงหน้า "อีก 7 วันจะถึงกำหนดชำระงวดที่ X"</li>
            <li>📢 <strong>3 วันก่อน</strong> - แจ้งเตือนใกล้ครบ "อีก 3 วันจะถึงกำหนดชำระ"</li>
            <li>📢 <strong>1 วันก่อน</strong> - แจ้งเตือน "พรุ่งนี้ครบกำหนดชำระงวดที่ X"</li>
            <li>📢 <strong>วันครบกำหนด</strong> - แจ้งเตือน "วันนี้ครบกำหนดชำระ กรุณาชำระตามยอด"</li>
        </ul>

        <p class="mt-4 font-semibold">หลังเลยกำหนดชำระ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>🔴 <strong>เลย 7 วัน</strong> - แจ้งเตือนเลยกำหนด "งวดที่ X เลยกำหนดชำระ 7 วันแล้ว กรุณาติดต่อกองทุน"</li>
            <li>🔴 <strong>เลย 14 วัน</strong> - แจ้งเตือนซ้ำ "เลยกำหนดชำระ 14 วัน กรุณาชำระโดยเร็ว"</li>
            <li>🔴 <strong>เลย 30 วัน</strong> - แจ้งเตือนด่วน "เลยกำหนดชำระ 30 วัน หากไม่ชำระอาจดำเนินการตามระเบียบกองทุน"</li>
        </ul>

        <x-guide-tip type="important">
            การแจ้งเตือน LINE จะทำงานอัตโนมัติ ไม่ต้องกดส่งเอง แต่สมาชิกต้อง <strong>เพิ่มเพื่อน LINE OA ของกองทุน</strong> ก่อน จึงจะได้รับข้อความ ถ้าสมาชิกยังไม่ได้เพิ่มเพื่อน ก็จะไม่ได้รับแจ้งเตือน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="5" title="วิธีดำเนินการเมื่อมีหนี้ค้างชำระ">
        <p>เมื่อพบว่ามีสมาชิกค้างชำระ ให้ดำเนินการตามลำดับดังนี้:</p>

        <p class="mt-4"><strong>ขั้นที่ 1: ติดต่อสมาชิกโดยตรง</strong></p>
        <ul class="list-disc list-inside space-y-2 my-2">
            <li>โทรศัพท์หาสมาชิก หรือส่งข้อความทาง LINE</li>
            <li>แจ้งยอดค้างชำระและขอให้มาชำระโดยเร็ว</li>
            <li>พูดด้วยน้ำเสียงสุภาพ เพราะสมาชิกอาจมีปัญหาทางการเงิน</li>
        </ul>

        <p class="mt-4"><strong>ขั้นที่ 2: นัดหมายวันชำระ</strong></p>
        <ul class="list-disc list-inside space-y-2 my-2">
            <li>ถ้าสมาชิกยังไม่พร้อมจ่ายทันที ให้นัดวันที่จะมาชำระ</li>
            <li>บันทึกวันนัดไว้เพื่อติดตามต่อ</li>
        </ul>

        <p class="mt-4"><strong>ขั้นที่ 3: บันทึกการติดตาม</strong></p>
        <ul class="list-disc list-inside space-y-2 my-2">
            <li>บันทึกว่าติดต่อสมาชิกเมื่อไหร่ พูดคุยเรื่องอะไร</li>
            <li>เป็นหลักฐานว่ากองทุนได้ดำเนินการติดตามแล้ว</li>
        </ul>

        <p class="mt-4"><strong>ขั้นที่ 4: ปรึกษาคณะกรรมการ (กรณีค้างนาน)</strong></p>
        <ul class="list-disc list-inside space-y-2 my-2">
            <li>ถ้าติดต่อไม่ได้ หรือสมาชิกไม่สามารถชำระได้</li>
            <li>ให้นำเรื่องเข้าที่ประชุมคณะกรรมการเพื่อพิจารณาแนวทาง</li>
            <li>อาจปรับโครงสร้างหนี้ ขยายเวลาผ่อน หรือดำเนินการตามระเบียบ</li>
        </ul>
    </x-guide-step>

    <x-guide-step :number="6" title="เข้าใจเรื่องหนี้สูญ">
        <p>หนี้ค้างชำระที่ปล่อยไว้นานอาจกลายเป็น <strong>หนี้สูญ</strong> ซึ่งมีผลกระทบดังนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>เงินที่กองทุนปล่อยกู้ไปจะเก็บกลับไม่ได้</li>
            <li>ทำให้กองทุนมีเงินหมุนเวียนน้อยลง</li>
            <li>มีผลต่องบการเงินและกำไรของกองทุนประจำปี</li>
            <li>อาจมีผลต่อการประเมินกองทุนหมู่บ้านดีเด่น</li>
        </ul>
        <x-guide-tip type="warning">
            หนี้ที่ค้างชำระนานเกิน <strong>90 วัน</strong> อาจถูกจัดเป็นหนี้สูญตามระเบียบ ควรติดตามทวงถามก่อนถึง 90 วัน
        </x-guide-tip>
        <x-guide-tip type="important">
            หนี้สูญมีผลกระทบโดยตรงต่อ <strong>งบการเงินและกำไรของกองทุน</strong> ทำให้เงินปันผลของสมาชิกทุกคนลดลง การป้องกันหนี้สูญจึงเป็นหน้าที่ของทุกฝ่ายในกองทุน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="7" title="เคล็ดลับการป้องกันหนี้ค้างชำระ">
        <ul class="list-disc list-inside space-y-3 my-4">
            <li><strong>ตรวจสอบรายการค้างชำระทุกสัปดาห์</strong> - อย่าปล่อยให้หนี้สะสม</li>
            <li><strong>ติดต่อสมาชิกทันทีเมื่อเลยกำหนด</strong> - ยิ่งรีบติดตามยิ่งมีโอกาสเก็บได้</li>
            <li><strong>แนะนำให้สมาชิกเพิ่มเพื่อน LINE OA</strong> - จะได้รับแจ้งเตือนอัตโนมัติ</li>
            <li><strong>ตรวจสอบความสามารถชำระหนี้ก่อนอนุมัติ</strong> - ป้องกันตั้งแต่ต้นทาง</li>
            <li><strong>สร้างวัฒนธรรมชำระตรงเวลา</strong> - ชื่นชมสมาชิกที่จ่ายตรงเวลาในที่ประชุม</li>
        </ul>
    </x-guide-step>
</div>

