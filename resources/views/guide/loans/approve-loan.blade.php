@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หน้านี้จะแนะนำวิธีอนุมัติสัญญาสินเชื่อ สำหรับคณะกรรมการหรือผู้มีอำนาจอนุมัติเท่านั้น
        อ่านทุกขั้นตอนให้เข้าใจก่อนกดอนุมัติ เพราะเมื่ออนุมัติแล้วจะยกเลิกได้ยาก
    </p>

    <x-guide-step :number="1" title="เข้าเมนูอนุมัติสินเชื่อ">
        <p>มองไปที่ <strong>แถบเมนูด้านซ้ายมือ</strong> ของหน้าจอ หาคำว่า <strong>"อนุมัติสินเชื่อ"</strong> แล้วคลิกหรือกดที่คำนั้น</p>
        <p>ถ้าใช้มือถือ ให้กดปุ่ม ☰ ที่มุมซ้ายบนก่อนเพื่อเปิดเมนู</p>
        <p>ถ้ามีสัญญารออนุมัติอยู่ จะเห็น <strong>ตัวเลขสีแดง</strong> เล็กๆ ที่เมนู บอกว่ามีกี่สัญญาที่รอดำเนินการ</p>
        <x-guide-screenshot src="images/guide/loans/menu-approve.png" alt="เมนูอนุมัติสินเชื่อ" caption="คลิกเมนู &quot;อนุมัติสินเชื่อ&quot; ตัวเลขสีแดงบอกจำนวนที่รออนุมัติ" />
        <x-guide-tip type="info">
            เมนูนี้จะแสดงเฉพาะผู้ที่มีสิทธิ์ <strong>"คณะกรรมการ"</strong> ขึ้นไปเท่านั้น ถ้าไม่เห็นเมนูนี้ แสดงว่าบัญชีของท่านไม่มีสิทธิ์อนุมัติ ให้ติดต่อผู้ดูแลระบบกองทุนเพื่อตั้งค่าสิทธิ์
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="2" title="ดูรายการคำขอสินเชื่อที่รออนุมัติ">
        <p>ระบบจะแสดงตารางรายการสัญญาที่รออนุมัติทั้งหมด แต่ละแถวจะมีข้อมูลดังนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>รหัสสัญญา</strong> - ตัวเลขรหัสอ้างอิงของสัญญา</li>
            <li><strong>ชื่อผู้กู้</strong> - ชื่อสมาชิกที่ขอกู้เงิน</li>
            <li><strong>จำนวนเงิน</strong> - จำนวนเงินที่ขอกู้</li>
            <li><strong>วันที่ขอกู้</strong> - วันที่สร้างสัญญา</li>
            <li><strong>สถานะ</strong> - จะแสดง "รออนุมัติ" เป็นสีเหลือง</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/pending-loan-list.png" alt="รายการสัญญารออนุมัติ" caption="ตารางแสดงรายการสัญญาที่รอคณะกรรมการอนุมัติ" />
        <x-guide-tip type="tip">
            ถ้ามีสัญญารออนุมัติหลายรายการ ให้ดำเนินการทีละรายการ อ่านรายละเอียดให้ครบก่อนตัดสินใจ
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="3" title="คลิกดูรายละเอียดสัญญา">
        <p>คลิกที่แถวของสัญญาที่ต้องการตรวจสอบ ระบบจะแสดงข้อมูลทั้งหมดของสัญญา:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>ข้อมูลผู้กู้:</strong> ชื่อ-นามสกุล, รหัสสมาชิก, เบอร์โทร</li>
            <li><strong>จำนวนเงินกู้:</strong> ยอดเงินที่ขอกู้ (บาท)</li>
            <li><strong>อัตราดอกเบี้ย:</strong> กี่เปอร์เซ็นต์ต่อปี</li>
            <li><strong>จำนวนงวด:</strong> จะผ่อนกี่เดือน</li>
            <li><strong>ผู้ค้ำประกัน:</strong> ชื่อสมาชิกที่ค้ำประกัน</li>
            <li><strong>ตารางผ่อนชำระ (ตัวอย่าง):</strong> แสดงว่าแต่ละงวดต้องจ่ายเท่าไหร่ เพื่อให้คณะกรรมการตรวจสอบความเหมาะสม</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/loan-detail-review.png" alt="รายละเอียดสัญญา" caption="ตรวจสอบรายละเอียดสัญญาให้ครบทุกรายการก่อนตัดสินใจ" />
    </x-guide-step>

    <x-guide-step :number="4" title="ตรวจสอบตามระเบียบกองทุน">
        <p>ก่อนอนุมัติ คณะกรรมการต้องตรวจสอบสิ่งต่อไปนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>จำนวนเงินกู้ <strong>อยู่ในวงเงิน</strong> ที่ระเบียบกองทุนกำหนดหรือไม่?</li>
            <li>อัตราดอกเบี้ย <strong>ตรงตามระเบียบ</strong> หรือไม่?</li>
            <li>จำนวนงวด <strong>เหมาะสม</strong> กับจำนวนเงินหรือไม่?</li>
            <li>ผู้ค้ำประกัน <strong>ครบตามจำนวน</strong> ที่ระเบียบกำหนดหรือไม่?</li>
            <li>ผู้กู้ <strong>มีสินเชื่ออื่นค้างชำระ</strong> อยู่หรือไม่?</li>
            <li>ผู้กู้ <strong>มีประวัติค้างชำระ</strong> มาก่อนหรือไม่?</li>
        </ul>
        <x-guide-tip type="warning">
            ตรวจสอบให้แน่ใจว่าผู้กู้ไม่มีสินเชื่อเดิมที่ยังค้างชำระอยู่ ระบบจะแสดงข้อมูลสินเชื่อเดิมของสมาชิก (ถ้ามี) ให้ตรวจสอบด้วย
        </x-guide-tip>
        <x-guide-tip type="tip">
            ดูข้อมูลรายได้และความสามารถในการผ่อนชำระของสมาชิก เทียบกับยอดผ่อนต่อเดือน เพื่อลดความเสี่ยงหนี้เสีย
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="5" title="คลิก &quot;อนุมัติ&quot; หรือ &quot;ไม่อนุมัติ&quot;">
        <p>เมื่อตรวจสอบเรียบร้อยแล้ว ให้เลือกดำเนินการอย่างใดอย่างหนึ่ง:</p>
        <ul class="list-disc list-inside space-y-4 my-4">
            <li>
                <strong>กดปุ่ม "อนุมัติ" (สีเขียว)</strong> - ถ้าข้อมูลถูกต้อง ผ่านเงื่อนไขทั้งหมด
            </li>
            <li>
                <strong>กดปุ่ม "ไม่อนุมัติ" (สีแดง)</strong> - ถ้าข้อมูลไม่ถูกต้องหรือไม่ผ่านเงื่อนไข
                <br>ระบบจะเปิดช่องให้พิมพ์ <strong>เหตุผลที่ไม่อนุมัติ</strong> ต้องใส่เหตุผลก่อนจึงจะกดยืนยันได้
                <br>ตัวอย่างเหตุผล: "วงเงินเกินระเบียบ", "มีสินเชื่อเดิมค้างชำระ", "ผู้ค้ำประกันไม่ครบ"
            </li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/btn-approve-reject.png" alt="ปุ่มอนุมัติและไม่อนุมัติ" caption="เลือกกด &quot;อนุมัติ&quot; (สีเขียว) หรือ &quot;ไม่อนุมัติ&quot; (สีแดง)" />
    </x-guide-step>

    <x-guide-step :number="6" title="ลงลายเซ็นอิเล็กทรอนิกส์ (กรณีอนุมัติ)">
        <p>ถ้ากดอนุมัติ ระบบจะแสดง <strong>หน้าลงลายเซ็น</strong> ขึ้นมา เป็นกล่องสีขาวให้วาดลายเซ็น</p>
        <p><strong>วิธีลงลายเซ็น:</strong></p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>ถ้าใช้มือถือหรือแท็บเล็ต:</strong> ใช้นิ้วมือวาดลายเซ็นในกล่องสีขาว เหมือนเซ็นชื่อบนกระดาษ</li>
            <li><strong>ถ้าใช้คอมพิวเตอร์:</strong> ใช้เมาส์กดค้างแล้วลากวาดลายเซ็นในกล่อง</li>
            <li>ถ้าวาดผิดหรือไม่สวย ให้กดปุ่ม <strong>"ล้าง"</strong> แล้ววาดใหม่ได้</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/signature-pad.png" alt="หน้าลงลายเซ็น" caption="วาดลายเซ็นในกล่องสีขาว ใช้นิ้วมือ (มือถือ) หรือเมาส์ (คอมพิวเตอร์)" />
        <x-guide-tip type="info">
            ลายเซ็นนี้จะถูกบันทึกเข้าระบบเป็นหลักฐานการอนุมัติ ผูกกับชื่อบัญชีของผู้อนุมัติ วันที่ และเวลาที่อนุมัติ
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="7" title="ยืนยันการอนุมัติ">
        <p>หลังลงลายเซ็นแล้ว ให้กดปุ่ม <strong>"ยืนยัน"</strong> ระบบจะถามอีกครั้งว่า "ยืนยันอนุมัติสัญญานี้?" ให้กด <strong>"ตกลง"</strong></p>
        <p>เมื่อยืนยันสำเร็จ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>สถานะสัญญาจะเปลี่ยนจาก "รออนุมัติ" เป็น <strong>"อนุมัติแล้ว"</strong></li>
            <li>ระบบบันทึกชื่อผู้อนุมัติ วันที่ เวลา และลายเซ็นเป็นหลักฐาน</li>
            <li>ผู้จัดการกองทุนจะสามารถดำเนินการ <strong>"เบิกจ่าย"</strong> เงินกู้ให้สมาชิกได้ในขั้นตอนถัดไป</li>
        </ul>
        <x-guide-tip type="important">
            เมื่ออนุมัติแล้ว <strong>ไม่สามารถยกเลิกการอนุมัติได้ง่าย</strong> ถ้าพบข้อผิดพลาดภายหลัง ต้องติดต่อผู้ดูแลระบบกองทุน ดังนั้นตรวจสอบข้อมูลให้แน่ใจก่อนกดอนุมัติ
        </x-guide-tip>
        <x-guide-tip type="info">
            <strong>ขั้นตอนถัดไป:</strong> หลังอนุมัติแล้ว ผู้จัดการกองทุนต้อง "เบิกจ่าย" เงินกู้ คือจ่ายเงินให้สมาชิกจริง เมื่อเบิกจ่ายแล้ว สัญญาจะเริ่มมีผล และสมาชิกจะต้องเริ่มผ่อนชำระตามตาราง
        </x-guide-tip>
    </x-guide-step>
</div>

