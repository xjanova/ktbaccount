@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หน้านี้จะแนะนำวิธีรับชำระเงินผ่อนสินเชื่อจากสมาชิก อ่านทุกขั้นตอนตามลำดับ
        เมื่อสมาชิกมาจ่ายเงิน ให้ทำตามนี้ได้เลย ระบบจะบันทึกบัญชีให้อัตโนมัติ
    </p>

    <x-guide-step :number="1" title="เข้าเมนูสินเชื่อ">
        <p>มองไปที่ <strong>แถบเมนูด้านซ้ายมือ</strong> ของหน้าจอ คลิกที่คำว่า <strong>"สินเชื่อ"</strong> ในหมวด "บริหารกองทุน"</p>
        <p>ถ้าใช้มือถือ ให้กดปุ่ม ☰ ที่มุมซ้ายบนก่อนเพื่อเปิดเมนู</p>
        <p>ระบบจะแสดงรายการสัญญาสินเชื่อทั้งหมดของกองทุน</p>
    </x-guide-step>

    <x-guide-step :number="2" title="ค้นหาสัญญาที่ต้องการรับชำระ">
        <p>ที่ด้านบนของตาราง มี <strong>ช่องค้นหา</strong> ให้พิมพ์ข้อมูลเพื่อหาสัญญา ทำได้หลายวิธี:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>พิมพ์ชื่อสมาชิก</strong> - เช่น "สมชาย" ระบบจะแสดงสัญญาของคนที่ชื่อตรง</li>
            <li><strong>พิมพ์รหัสสัญญา</strong> - เช่น "LN-0001" ถ้าจำรหัสได้</li>
        </ul>
        <p>เมื่อเจอสัญญาที่ต้องการ ให้คลิกที่แถวนั้นเพื่อเปิดดูรายละเอียด</p>
        <x-guide-screenshot src="images/guide/loans/select-loan-contract.png" alt="เลือกสัญญาสินเชื่อ" caption="ค้นหาสัญญาโดยพิมพ์ชื่อหรือรหัสสัญญา แล้วคลิกเลือก" />
    </x-guide-step>

    <x-guide-step :number="3" title="ดูรายละเอียดสัญญา">
        <p>หน้ารายละเอียดสัญญาจะแสดงข้อมูลสรุปที่สำคัญ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>ยอดเงินกู้ทั้งหมด</strong> - จำนวนเงินที่กู้ตอนแรก</li>
            <li><strong>ยอดชำระแล้ว</strong> - จำนวนเงินที่สมาชิกจ่ายมาแล้วรวมทั้งหมด</li>
            <li><strong>ยอดคงเหลือ</strong> - จำนวนเงินที่ยังเหลือต้องจ่าย</li>
            <li><strong>งวดที่ค้างชำระ</strong> - จำนวนงวดที่ยังไม่ได้จ่าย</li>
            <li><strong>วันครบกำหนดถัดไป</strong> - วันที่ต้องจ่ายงวดถัดไป</li>
        </ul>
        <x-guide-tip type="tip">
            ตรวจสอบข้อมูลนี้กับสมาชิกก่อนรับชำระ เพื่อให้ทั้งสองฝ่ายเข้าใจตรงกันว่าค้างกี่งวดและต้องจ่ายเท่าไหร่
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="4" title="คลิกปุ่ม &quot;รับชำระ&quot;">
        <p>ในหน้ารายละเอียดสัญญา ให้คลิกปุ่ม <strong>"รับชำระ"</strong> สีเขียว</p>
        <p>ระบบจะเปิดแบบฟอร์มรับชำระเงินขึ้นมา</p>
        <x-guide-screenshot src="images/guide/loans/btn-receive-payment.png" alt="ปุ่มรับชำระ" caption="คลิกปุ่ม &quot;รับชำระ&quot; สีเขียวเพื่อเริ่มบันทึกการรับเงิน" />
        <x-guide-tip type="info">
            ปุ่ม "รับชำระ" จะแสดงเฉพาะสัญญาที่มีสถานะ "อนุมัติแล้ว" หรือ "กำลังผ่อนชำระ" เท่านั้น สัญญาที่ยัง "รออนุมัติ" จะยังรับชำระไม่ได้
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="5" title="ดูรายการงวดค้างชำระ">
        <p>ระบบจะแสดงตารางงวดค้างชำระทั้งหมด แต่ละแถวมีข้อมูลดังนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>งวดที่</strong> - ลำดับงวดการชำระ เช่น งวดที่ 1, 2, 3</li>
            <li><strong>เงินต้น</strong> - ส่วนที่เป็นเงินต้นที่ต้องจ่ายในงวดนั้น</li>
            <li><strong>ดอกเบี้ย</strong> - ส่วนที่เป็นดอกเบี้ยในงวดนั้น</li>
            <li><strong>รวม</strong> - เงินต้น + ดอกเบี้ย = จำนวนเงินที่ต้องจ่ายต่องวด</li>
            <li><strong>สถานะ</strong> - บอกสถานะของแต่ละงวด</li>
        </ul>
        <p>สีของสถานะมีความหมายดังนี้:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><span class="inline-block w-4 h-4 bg-green-500 rounded mr-2 align-middle"></span><strong>สีเขียว = ชำระแล้ว</strong> - งวดนี้จ่ายเงินเรียบร้อยแล้ว</li>
            <li><span class="inline-block w-4 h-4 bg-yellow-500 rounded mr-2 align-middle"></span><strong>สีเหลือง = รอชำระ</strong> - ยังไม่ถึงกำหนดหรือรอสมาชิกมาจ่าย</li>
            <li><span class="inline-block w-4 h-4 bg-red-500 rounded mr-2 align-middle"></span><strong>สีแดง = เลยกำหนด</strong> - เลยวันที่ต้องจ่ายแล้วแต่ยังไม่ได้ชำระ</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/overdue-installments.png" alt="งวดค้างชำระ" caption="ตารางงวดค้างชำระ สีบอกสถานะของแต่ละงวด" />
    </x-guide-step>

    <x-guide-step :number="6" title="ใส่จำนวนเงินที่ได้รับ">
        <p>ในช่อง <strong>"จำนวนเงิน"</strong> ให้พิมพ์จำนวนเงินที่สมาชิกจ่ายมาจริง</p>
        <p>ใส่เป็นตัวเลข เช่น <strong>9333.33</strong> (ไม่ต้องใส่เครื่องหมายจุลภาค หรือคำว่า "บาท")</p>

        <p class="mt-4"><strong>กรณีต่างๆ ที่อาจเกิดขึ้น:</strong></p>
        <ul class="list-disc list-inside space-y-3 my-4">
            <li>
                <strong>ชำระตามยอดงวดปกติ:</strong> ใส่ตัวเลขตามยอดรวมที่ระบบแสดง เช่น ถ้างวดละ 9,333.33 บาท ก็ใส่ <strong>9333.33</strong>
            </li>
            <li>
                <strong>ชำระหลายงวดพร้อมกัน:</strong> ใส่ยอดรวมของหลายงวด เช่น ถ้าค้าง 3 งวดและจ่ายหมด ก็ใส่ยอดรวม 3 งวด ระบบจะตัดยอดให้อัตโนมัติ
            </li>
            <li>
                <strong>ชำระบางส่วน (น้อยกว่ายอดงวด):</strong> ใส่จำนวนที่รับมาจริง ระบบจะบันทึกว่าจ่ายบางส่วน และยังเหลือยอดค้างในงวดนั้น
            </li>
            <li>
                <strong>ชำระเกินยอดงวด:</strong> ถ้าสมาชิกจ่ายมากกว่ายอดงวด ส่วนเกินจะถูกนำไปตัดงวดถัดไปให้อัตโนมัติ
            </li>
        </ul>
        <x-guide-tip type="tip">
            ปกติให้ใส่ตามยอดงวดที่ระบบแสดง แต่ถ้าสมาชิกจ่ายไม่ครบหรือจ่ายเกิน ก็ใส่ตามจริงได้ ระบบจัดการให้เอง
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="7" title="เลือกวิธีรับเงิน">
        <p>ช่อง <strong>"ช่องทางรับเงิน"</strong> ให้เลือกว่ารับเงินจากสมาชิกด้วยวิธีไหน:</p>
        <ul class="list-disc list-inside space-y-3 my-4">
            <li>
                <strong>เงินสด</strong> - สมาชิกจ่ายเป็นเงินสดโดยตรงที่กองทุน เลือกข้อนี้แล้วไม่ต้องกรอกอะไรเพิ่ม
            </li>
            <li>
                <strong>เงินฝากธนาคาร</strong> - สมาชิกโอนเงินเข้าบัญชีธนาคารของกองทุน
                <br>เมื่อเลือกข้อนี้ จะมีช่องเพิ่มเติมให้เลือก <strong>บัญชีธนาคาร</strong> ที่รับเงินเข้า (ถ้ากองทุนมีหลายบัญชี)
            </li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/payment-channel.png" alt="เลือกช่องทางรับเงิน" caption="เลือก &quot;เงินสด&quot; หรือ &quot;เงินฝากธนาคาร&quot; ตามที่สมาชิกจ่ายมาจริง" />
        <x-guide-tip type="warning">
            เลือกช่องทางให้ตรงกับความเป็นจริง เพราะระบบจะบันทึกบัญชีตามช่องทางที่เลือก ถ้าเลือกผิด บัญชีจะไม่ตรง
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="8" title="ใส่เลขที่ใบเสร็จ (ถ้ามี)">
        <p>ช่อง <strong>"เลขที่ใบเสร็จ"</strong> สำหรับใส่เลขที่ใบเสร็จรับเงินที่ออกให้สมาชิก (ถ้ากองทุนมีระบบออกใบเสร็จ)</p>
        <p>ช่องนี้ <strong>ไม่บังคับ</strong> ถ้าไม่มีใบเสร็จก็ปล่อยว่างได้</p>
        <x-guide-tip type="tip">
            แนะนำให้ใส่เลขที่ใบเสร็จทุกครั้งที่มี เพื่อให้ง่ายต่อการตรวจสอบภายหลัง และเป็นหลักฐานการรับเงิน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="9" title="ตรวจสอบข้อมูลก่อนบันทึก">
        <p>ก่อนกดบันทึก ให้ตรวจสอบข้อมูลทั้งหมดอีกครั้ง:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>จำนวนเงินที่ใส่ ตรงกับเงินที่รับมาจริงหรือไม่?</li>
            <li>ช่องทางรับเงิน ถูกต้องหรือไม่?</li>
            <li>ถ้าเป็นเงินโอนธนาคาร เลือกบัญชีถูกหรือไม่?</li>
        </ul>
    </x-guide-step>

    <x-guide-step :number="10" title="กดบันทึกการรับชำระ">
        <p>เมื่อตรวจสอบเรียบร้อยแล้ว ให้กดปุ่ม <strong>"บันทึก"</strong></p>
        <p>ถ้าข้อมูลถูกต้อง ระบบจะบันทึกสำเร็จและแสดงหน้ายืนยัน</p>
        <p>ถ้ามีข้อผิดพลาด ระบบจะแจ้งเตือนเป็นข้อความสีแดง ให้แก้ไขตามที่แจ้งแล้วกดบันทึกอีกครั้ง</p>
        <x-guide-screenshot src="images/guide/loans/btn-save-payment.png" alt="ปุ่มบันทึก" caption="ตรวจสอบข้อมูลให้ครบแล้วกดปุ่ม &quot;บันทึก&quot;" />
        <x-guide-tip type="important">
            เมื่อบันทึกแล้ว ระบบจะ <strong>บันทึกบัญชีให้อัตโนมัติ</strong> โดยลงรายการ:
            <br>- เดบิต (Dr.) เงินสดหรือเงินฝากธนาคาร (เงินเข้ากองทุน)
            <br>- เครดิต (Cr.) ลูกหนี้เงินกู้ (ลดยอดหนี้) + รายได้ดอกเบี้ย
            <br>ไม่ต้องไปลงบัญชีเพิ่มเอง ระบบจัดการให้ทั้งหมด
        </x-guide-tip>
        <x-guide-tip type="info">
            ถ้ากองทุนเปิดใช้งานการแจ้งเตือนผ่าน LINE สมาชิกจะได้รับข้อความแจ้งว่า "รับชำระเรียบร้อยแล้ว" พร้อมยอดเงินและยอดคงเหลือทาง LINE อัตโนมัติ
        </x-guide-tip>
        <x-guide-tip type="tip">
            หลังบันทึกสำเร็จ สามารถกดปุ่ม <strong>"พิมพ์ใบเสร็จ"</strong> เพื่อดาวน์โหลดใบเสร็จรับเงินเป็นไฟล์ PDF แล้วพิมพ์ออกมาให้สมาชิกได้
        </x-guide-tip>
    </x-guide-step>
</div>

