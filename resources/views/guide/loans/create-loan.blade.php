@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หน้านี้จะแนะนำวิธีสร้างสัญญาสินเชื่อใหม่ให้สมาชิกแบบละเอียดทุกขั้นตอน
        อ่านตามลำดับแล้วทำตามได้เลย ไม่ต้องมีความรู้คอมพิวเตอร์มาก่อน
    </p>

    <x-guide-step :number="1" title="เข้าเมนูสินเชื่อ">
        <p>มองไปที่ <strong>แถบเมนูด้านซ้ายมือ</strong> ของหน้าจอ (ถ้าใช้มือถือให้กดปุ่ม ☰ ที่มุมซ้ายบนก่อน)</p>
        <p>หาคำว่า <strong>"สินเชื่อ"</strong> แล้วคลิกหรือกดที่คำนั้น อยู่ในหมวด <strong>"บริหารกองทุน"</strong></p>
        <p>เมื่อคลิกแล้ว ระบบจะแสดงหน้ารายการสัญญาสินเชื่อทั้งหมดของกองทุน ถ้ายังไม่เคยสร้างสัญญาเลย หน้านี้จะว่างเปล่า ไม่ต้องตกใจ</p>
        <x-guide-screenshot src="images/guide/loans/menu-loan.png" alt="เมนูสินเชื่อ" caption="คลิกเมนู &quot;สินเชื่อ&quot; ในแถบด้านข้างซ้ายมือ อยู่หมวด &quot;บริหารกองทุน&quot;" />
    </x-guide-step>

    <x-guide-step :number="2" title="คลิกปุ่ม &quot;+ สร้างสัญญาใหม่&quot;">
        <p>มองไปที่ <strong>มุมขวาบน</strong> ของหน้าจอ จะเห็นปุ่มสีม่วงเขียนว่า <strong>"+ สร้างสัญญาใหม่"</strong></p>
        <p>คลิกหรือกดที่ปุ่มนั้น ระบบจะเปิดแบบฟอร์มให้กรอกข้อมูลสัญญา</p>
        <x-guide-screenshot src="images/guide/loans/btn-create-loan.png" alt="ปุ่มสร้างสัญญา" caption="ปุ่ม &quot;+ สร้างสัญญาใหม่&quot; อยู่ที่มุมขวาบนของหน้า" />
        <x-guide-tip type="info">
            ถ้าไม่เห็นปุ่มนี้ แสดงว่าบัญชีของท่านอาจไม่มีสิทธิ์สร้างสัญญา ต้องเป็น "ผู้จัดการกองทุน" หรือ "ผู้จัดทำบัญชี" ขึ้นไป
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="3" title="เลือกสมาชิกผู้กู้">
        <p>ช่องแรกคือ <strong>"ผู้กู้"</strong> ให้พิมพ์ชื่อหรือนามสกุลของสมาชิกที่ต้องการกู้เงินลงในช่อง</p>
        <p>พอพิมพ์ไป 2-3 ตัวอักษร ระบบจะแสดงรายชื่อที่ตรงกันขึ้นมาเป็น <strong>รายการให้เลือก (dropdown)</strong> ด้านล่างช่อง</p>
        <p>ให้คลิกหรือกดที่ชื่อสมาชิกที่ถูกต้อง ชื่อจะถูกเติมลงในช่องให้อัตโนมัติ</p>
        <x-guide-screenshot src="images/guide/loans/select-member.png" alt="เลือกสมาชิกผู้กู้" caption="พิมพ์ชื่อสมาชิก แล้วเลือกจากรายการที่แสดงด้านล่าง" />
        <x-guide-tip type="tip">
            สมาชิกต้องลงทะเบียนในระบบก่อนถึงจะกู้เงินได้ ถ้าพิมพ์ชื่อแล้วไม่ขึ้น แสดงว่ายังไม่ได้เพิ่มสมาชิกคนนี้ ให้ไปที่เมนู "สมาชิก" เพิ่มข้อมูลก่อน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="4" title="เลือกชุดบัญชี">
        <p>ช่องถัดมาคือ <strong>"ชุดบัญชี"</strong> ให้เลือกว่าเงินกู้นี้มาจากเงินกองทุนส่วนไหน</p>
        <p>กดที่ช่อง จะมีรายการให้เลือก ตัวอย่างเช่น:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>เงินล้าน (กทบ.)</strong> - เงินที่ได้รับจากกองทุนหมู่บ้านฯ 1 ล้านบาท</li>
            <li><strong>เงินเพิ่มทุน</strong> - เงินเพิ่มทุนที่กองทุนได้รับเพิ่มภายหลัง</li>
            <li><strong>เงินออมทรัพย์</strong> - เงินที่กองทุนนำเงินออมมาปล่อยกู้</li>
        </ul>
        <p>ให้เลือกตามที่กองทุนของท่านกำหนด ถ้าไม่แน่ใจ ให้ถามผู้ดูแลกองทุน</p>
        <x-guide-tip type="info">
            แต่ละชุดบัญชีอาจมีระเบียบการกู้เงินต่างกัน เช่น วงเงินสูงสุด อัตราดอกเบี้ย จำนวนงวด ระบบจะตรวจสอบตามระเบียบของชุดบัญชีที่เลือกให้อัตโนมัติ
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="5" title="กรอกจำนวนเงินกู้">
        <p>ช่อง <strong>"จำนวนเงินกู้ (บาท)"</strong> ให้พิมพ์จำนวนเงินที่สมาชิกต้องการกู้</p>
        <p>วิธีพิมพ์:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>พิมพ์เป็นตัวเลขเท่านั้น เช่น <strong>50000</strong> หรือ <strong>100000</strong></li>
            <li>ถ้ามีสตางค์ ให้ใส่จุดทศนิยม 2 ตำแหน่ง เช่น <strong>50000.00</strong></li>
            <li><strong>ห้ามใส่</strong> เครื่องหมายจุลภาค (,) หรือคำว่า "บาท"</li>
            <li>ตัวอย่างที่ถูก: <strong>100000</strong> หรือ <strong>100000.00</strong></li>
            <li>ตัวอย่างที่ผิด: <del>100,000</del> หรือ <del>100,000 บาท</del></li>
        </ul>
        <x-guide-tip type="tip">
            ตรวจสอบวงเงินสูงสุดที่สมาชิกสามารถกู้ได้ตามระเบียบของกองทุน เช่น บางกองทุนกำหนดกู้ได้ไม่เกิน 50,000 บาท ถ้าใส่เกินวงเงิน ระบบจะแจ้งเตือนไม่ให้บันทึก
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="6" title="กรอกอัตราดอกเบี้ย">
        <p>ช่อง <strong>"อัตราดอกเบี้ย (% ต่อปี)"</strong> ให้ใส่ตัวเลขดอกเบี้ยต่อปี</p>
        <p>ตัวอย่าง: ถ้าดอกเบี้ย 12% ต่อปี ให้พิมพ์ <strong>12</strong> (ไม่ต้องใส่เครื่องหมาย %)</p>
        <p>ถ้าดอกเบี้ย 9.5% ต่อปี ให้พิมพ์ <strong>9.5</strong></p>
        <x-guide-tip type="info">
            ระบบคำนวณดอกเบี้ยแบบ <strong>อัตราคงที่ (flat rate)</strong> หมายความว่า ดอกเบี้ยทุกงวดจะเท่ากันตลอดสัญญา
        </x-guide-tip>
        <x-guide-tip type="tip">
            <strong>ตัวอย่างการคำนวณ:</strong> กู้ 100,000 บาท ดอกเบี้ย 12% ต่อปี<br>
            ดอกเบี้ยต่อเดือน = 100,000 x 12% / 12 เดือน = <strong>1,000 บาทต่อเดือน</strong><br>
            ถ้าผ่อน 12 งวด เงินต้นต่องวด = 100,000 / 12 = 8,333.33 บาท<br>
            รวมต้องจ่ายต่องวด = 8,333.33 + 1,000 = <strong>9,333.33 บาท</strong>
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="7" title="กรอกจำนวนงวด (เดือน)">
        <p>ช่อง <strong>"จำนวนงวด"</strong> คือจำนวนเดือนที่สมาชิกจะผ่อนชำระ</p>
        <p>ตัวอย่าง: ถ้าผ่อน 1 ปี ให้ใส่ <strong>12</strong> ถ้าผ่อน 2 ปี ให้ใส่ <strong>24</strong></p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>จำนวนงวดน้อยสุดคือ <strong>1 งวด</strong> (จ่ายครั้งเดียวจบ)</li>
            <li>จำนวนงวดมากสุดขึ้นอยู่กับระเบียบกองทุน</li>
        </ul>
        <x-guide-tip type="tip">
            ส่วนใหญ่กองทุนหมู่บ้านกำหนดผ่อนไม่เกิน 60 งวด (5 ปี) ถ้าจำนวนเงินกู้น้อย อาจผ่อน 6-12 งวด ถ้าเงินกู้มากอาจผ่อน 24-60 งวด
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="8" title="เลือกผู้ค้ำประกัน">
        <p>ช่อง <strong>"ผู้ค้ำประกัน"</strong> ให้เลือกสมาชิกที่จะมาค้ำประกันให้ผู้กู้ โดยวิธีเดียวกับการเลือกผู้กู้ คือพิมพ์ชื่อแล้วเลือกจากรายการ</p>
        <p>สามารถเลือกผู้ค้ำประกันได้ <strong>1-2 คน</strong> ตามระเบียบกองทุน</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>ผู้ค้ำประกัน <strong>ต้องเป็นสมาชิก</strong> ของกองทุนเท่านั้น</li>
            <li>ผู้กู้ <strong>ห้ามค้ำประกันให้ตัวเอง</strong></li>
            <li>ผู้ค้ำประกันควรรับรู้และยินยอมก่อนที่จะถูกเลือก</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/select-guarantor.png" alt="เลือกผู้ค้ำประกัน" caption="พิมพ์ชื่อผู้ค้ำประกันแล้วเลือกจากรายการ เลือกได้ 1-2 คน" />
        <x-guide-tip type="warning">
            ผู้ค้ำประกันมีความรับผิดชอบตามกฎหมาย ถ้าผู้กู้ไม่ชำระเงิน กองทุนมีสิทธิ์เรียกเก็บเงินจากผู้ค้ำประกันแทน ดังนั้นต้องแจ้งให้ผู้ค้ำประกันทราบและยินยอมก่อนเสมอ
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="9" title="ตรวจสอบข้อมูลทั้งหมดก่อนบันทึก">
        <p>ก่อนกดบันทึก ให้ <strong>อ่านข้อมูลทั้งหมดอีกครั้ง</strong> ตรวจสอบให้แน่ใจว่า:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li>ชื่อผู้กู้ ถูกคนหรือไม่?</li>
            <li>ชุดบัญชี ถูกต้องหรือไม่?</li>
            <li>จำนวนเงิน ตรงกับที่ตกลงกันหรือไม่?</li>
            <li>อัตราดอกเบี้ย ตรงตามระเบียบหรือไม่?</li>
            <li>จำนวนงวด เหมาะสมหรือไม่?</li>
            <li>ผู้ค้ำประกัน ครบถ้วนและถูกคนหรือไม่?</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/btn-save-loan.png" alt="ตรวจสอบข้อมูล" caption="อ่านข้อมูลทุกช่องอีกครั้งก่อนกดบันทึก" />
        <x-guide-tip type="warning">
            ถ้าข้อมูลผิดแล้วบันทึกไปแล้ว จะแก้ไขได้ยาก ต้องยกเลิกสัญญาแล้วสร้างใหม่ ดังนั้นตรวจสอบให้ดีก่อนบันทึก
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="10" title="กดบันทึกสัญญา">
        <p>เมื่อตรวจสอบข้อมูลเรียบร้อยแล้ว ให้กดปุ่ม <strong>"บันทึก"</strong> สีเขียวที่ด้านล่างของแบบฟอร์ม</p>
        <p>ถ้าข้อมูลถูกต้องครบถ้วน ระบบจะบันทึกสัญญาสำเร็จและแสดงหน้ารายละเอียดสัญญา</p>
        <p>ถ้ามีข้อผิดพลาด ระบบจะแจ้งเตือนเป็นข้อความสีแดงที่ช่องที่มีปัญหา ให้แก้ไขตามที่แจ้งแล้วกดบันทึกอีกครั้ง</p>
        <x-guide-tip type="important">
            สัญญาที่สร้างใหม่จะมีสถานะ <strong>"รออนุมัติ"</strong> ยังไม่มีผลบังคับใช้ ต้องรอให้คณะกรรมการอนุมัติก่อน จึงจะสามารถเบิกจ่ายเงินกู้และเริ่มรับชำระได้
        </x-guide-tip>
        <x-guide-tip type="info">
            <strong>ขั้นตอนทั้งหมดของสินเชื่อ:</strong><br>
            1. สร้างสัญญา (ขั้นตอนนี้) → 2. รออนุมัติ → 3. คณะกรรมการอนุมัติ → 4. เบิกจ่ายเงินกู้ให้สมาชิก → 5. สมาชิกผ่อนชำระรายเดือน → 6. ชำระครบปิดสัญญา
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="11" title="ดูสัญญาที่สร้างสำเร็จ">
        <p>หลังบันทึกเรียบร้อย ระบบจะแสดงหน้ารายละเอียดของสัญญาที่สร้างสำเร็จ ประกอบด้วย:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>รหัสสัญญา</strong> - รหัสที่ระบบสร้างให้อัตโนมัติ ใช้อ้างอิงสัญญา</li>
            <li><strong>ข้อมูลผู้กู้และผู้ค้ำประกัน</strong></li>
            <li><strong>รายละเอียดสินเชื่อ</strong> - จำนวนเงิน ดอกเบี้ย งวด</li>
            <li><strong>ตารางผ่อนชำระ</strong> - ระบบคำนวณให้อัตโนมัติ แสดงว่าแต่ละงวดต้องจ่ายเท่าไหร่</li>
            <li><strong>สถานะ: รออนุมัติ</strong> - รอคณะกรรมการตรวจสอบและอนุมัติ</li>
        </ul>
        <x-guide-screenshot src="images/guide/loans/loan-created-success.png" alt="สัญญาที่สร้างสำเร็จ" caption="สัญญาสินเชื่อที่สร้างสำเร็จ พร้อมตารางผ่อนชำระที่ระบบคำนวณให้" />
        <x-guide-tip type="tip">
            ระบบคำนวณตารางผ่อนชำระให้อัตโนมัติ ไม่ต้องคิดเลขเอง แต่ควรตรวจสอบยอดรวมว่าถูกต้องตามที่ตกลงกับสมาชิก
        </x-guide-tip>
    </x-guide-step>
</div>

