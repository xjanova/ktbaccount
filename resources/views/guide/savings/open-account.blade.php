@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หน้านี้จะแนะนำวิธีเปิดบัญชีเงินฝากให้สมาชิกกองทุนหมู่บ้าน
        ทำตามขั้นตอนด้านล่างทีละขั้น ไม่ยากเลย
        ถ้าสมาชิกคนไหนอยากฝากเงินกับกองทุน ต้องเปิดบัญชีก่อนเป็นอันดับแรก
    </p>

    <x-guide-step :number="1" title="เข้าเมนู &quot;เงินฝาก&quot;">
        <p>มองไปที่ <strong>แถบเมนูด้านซ้ายมือ</strong> ของหน้าจอ (sidebar)</p>
        <p>หาหมวดที่เขียนว่า <strong>"บริการการเงิน"</strong> แล้วคลิกที่คำว่า <strong>"เงินฝาก"</strong></p>
        <p>ถ้าหมวด "บริการการเงิน" ยุบอยู่ (มองไม่เห็นเมนูย่อย) ให้คลิกที่ชื่อหมวดก่อน 1 ครั้ง เมนูย่อยจะเปิดออกมา</p>
        <p>เมื่อคลิกแล้ว ระบบจะแสดง <strong>หน้ารายการบัญชีเงินฝากทั้งหมด</strong> ของกองทุน</p>
        <x-guide-screenshot src="images/guide/savings/menu-savings.png" alt="เมนูเงินฝาก" caption="คลิกเมนู &quot;เงินฝาก&quot; ในแถบด้านซ้าย หมวด &quot;บริการการเงิน&quot;" />
    </x-guide-step>

    <x-guide-step :number="2" title="คลิกปุ่ม &quot;+ เปิดบัญชี&quot;">
        <p>มองไปที่ <strong>มุมขวาบน</strong> ของหน้าจอ จะเห็นปุ่มสีม่วงเขียนว่า <strong>"+ เปิดบัญชี"</strong></p>
        <p>คลิกที่ปุ่มนี้ 1 ครั้ง ระบบจะเปิดแบบฟอร์มเปิดบัญชีเงินฝากใหม่ขึ้นมา</p>
        <x-guide-screenshot src="images/guide/savings/btn-open-account.png" alt="ปุ่มเปิดบัญชี" caption="ปุ่ม &quot;+ เปิดบัญชี&quot; อยู่มุมขวาบนของหน้า" />
    </x-guide-step>

    <x-guide-step :number="3" title="เลือกสมาชิกที่จะเปิดบัญชีให้">
        <p>ในแบบฟอร์ม จะมีช่อง <strong>"สมาชิก"</strong> ให้เลือก</p>
        <p>วิธีค้นหาสมาชิก:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li><strong>พิมพ์ชื่อ</strong> - เช่น พิมพ์ "สมชาย" ระบบจะแสดงรายชื่อสมาชิกที่มีคำว่า "สมชาย" ให้เลือก</li>
            <li><strong>พิมพ์รหัสสมาชิก</strong> - เช่น พิมพ์ "M001" ระบบจะค้นหาจากรหัสสมาชิก</li>
        </ul>
        <p class="mt-2">เมื่อเจอชื่อที่ต้องการแล้ว ให้ <strong>คลิกที่ชื่อนั้น 1 ครั้ง</strong> เพื่อเลือก</p>
        <x-guide-screenshot src="images/guide/savings/select-member-savings.png" alt="เลือกสมาชิก" caption="พิมพ์ชื่อหรือรหัสสมาชิก แล้วคลิกเลือกจากรายการ" />
        <x-guide-tip type="info">
            สมาชิก 1 คน สามารถเปิดบัญชีเงินฝากได้หลายบัญชี เช่น เปิดบัญชีออมทรัพย์ 1 บัญชี และบัญชีประจำอีก 1 บัญชี ก็ได้
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="4" title="เลือกประเภทบัญชี">
        <p>คลิกที่ช่อง <strong>"ประเภทบัญชี"</strong> จะมีตัวเลือกให้เลือก:</p>
        <ul class="list-disc pl-5 space-y-3 mt-2">
            <li>
                <strong>ออมทรัพย์</strong> - บัญชีแบบปกติ ฝากถอนได้ตลอดเวลา ไม่มีกำหนด
                ดอกเบี้ยต่ำกว่าประจำ เหมาะกับสมาชิกที่อยากเก็บเงินแต่อาจต้องใช้เงินบ่อย
            </li>
            <li>
                <strong>ประจำ</strong> - บัญชีแบบฝากเป็นระยะเวลา (เช่น ฝาก 6 เดือน หรือ 1 ปี)
                ดอกเบี้ยสูงกว่าออมทรัพย์ เหมาะกับสมาชิกที่ไม่ต้องใช้เงินเร็ว
                (ประเภทนี้จะมีหรือไม่มีขึ้นอยู่กับกองทุนแต่ละแห่งกำหนด)
            </li>
        </ul>
        <x-guide-screenshot src="images/guide/savings/account-type.png" alt="ประเภทบัญชี" caption="เลือกประเภทบัญชี: ออมทรัพย์ หรือ ประจำ" />
    </x-guide-step>

    <x-guide-step :number="5" title="กำหนดอัตราดอกเบี้ย">
        <p>ช่อง <strong>"อัตราดอกเบี้ย (% ต่อปี)"</strong> ให้ใส่ตัวเลขเป็น <strong>เปอร์เซ็นต์ต่อปี</strong></p>
        <p>วิธีใส่:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>ถ้าดอกเบี้ย <strong>2% ต่อปี</strong> → ให้ใส่ <strong>2</strong></li>
            <li>ถ้าดอกเบี้ย <strong>3.5% ต่อปี</strong> → ให้ใส่ <strong>3.5</strong></li>
            <li>ถ้า <strong>ไม่มีดอกเบี้ย</strong> → ให้ใส่ <strong>0</strong></li>
        </ul>
        <x-guide-tip type="tip">
            อัตราดอกเบี้ยต้องเป็นไปตามที่กองทุนกำหนดในระเบียบ ถ้าไม่แน่ใจให้ถามประธานกองทุนหรือดูจากระเบียบกองทุน
        </x-guide-tip>
        <x-guide-tip type="info">
            ถ้ากองทุนตั้งค่าอัตราดอกเบี้ยไว้ล่วงหน้าแล้ว ระบบจะใส่ตัวเลขให้อัตโนมัติ ไม่ต้องพิมพ์เอง
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="6" title="เลือกชุดบัญชี (ถ้ามี)">
        <p>ถ้ากองทุนมีหลายชุดบัญชี ระบบจะแสดงช่อง <strong>"ชุดบัญชี"</strong> ให้เลือก</p>
        <p>ให้เลือกชุดบัญชีที่ต้องการ เช่น "ชุดบัญชีหลัก" หรือ "ชุดบัญชีย่อย"</p>
        <p>ถ้ากองทุนมีชุดบัญชีเดียว ระบบจะเลือกให้อัตโนมัติ ไม่ต้องทำอะไร</p>
    </x-guide-step>

    <x-guide-step :number="7" title="ตรวจสอบข้อมูลและกดบันทึก">
        <p>ก่อนกดบันทึก ให้ตรวจสอบข้อมูลทั้งหมดอีกครั้ง:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>ชื่อสมาชิก - ถูกคนหรือไม่?</li>
            <li>ประเภทบัญชี - ถูกประเภทหรือไม่?</li>
            <li>อัตราดอกเบี้ย - ถูกต้องตามระเบียบหรือไม่?</li>
        </ul>
        <p class="mt-3">ถ้าถูกต้องแล้ว ให้คลิกปุ่ม <strong>"บันทึก"</strong> สีเขียว</p>
        <x-guide-screenshot src="images/guide/savings/btn-save-account.png" alt="ปุ่มบันทึก" caption="ตรวจสอบข้อมูลให้ครบ แล้วกดปุ่ม &quot;บันทึก&quot;" />
        <p class="mt-3">เมื่อบันทึกสำเร็จ ระบบจะทำสิ่งต่อไปนี้:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>สร้าง <strong>เลขที่บัญชี</strong> ให้อัตโนมัติ เช่น SAV-000001, SAV-000002 (ไม่ต้องตั้งเอง)</li>
            <li>ตั้ง <strong>ยอดเงินเริ่มต้นเป็น 0 บาท</strong></li>
            <li>แสดงข้อความ <strong>"เปิดบัญชีสำเร็จ"</strong> สีเขียว</li>
        </ul>
        <x-guide-tip type="info">
            ยอดเงินเริ่มต้นจะเป็น 0 บาท ถ้าสมาชิกต้องการฝากเงินเข้าบัญชี ต้องทำรายการ "ฝากเงิน" แยกต่างหาก (ดูวิธีในหน้า "ฝากเงิน")
        </x-guide-tip>
    </x-guide-step>

    <h3 class="text-xl font-bold text-white mt-10 mb-4">วิธีดูรายชื่อบัญชีเงินฝากทั้งหมด</h3>
    <p>หลังเปิดบัญชีแล้ว สามารถกลับมาดูรายชื่อบัญชีทั้งหมดได้โดย:</p>
    <ul class="list-disc pl-5 space-y-2 mt-2">
        <li>คลิกเมนู <strong>"เงินฝาก"</strong> ในแถบด้านซ้าย</li>
        <li>ระบบจะแสดงตารางบัญชีทั้งหมด มีข้อมูล: เลขบัญชี, ชื่อสมาชิก, ประเภท, ยอดคงเหลือ, สถานะ</li>
        <li>สามารถ <strong>ค้นหา</strong> ได้โดยพิมพ์ชื่อสมาชิกหรือเลขบัญชีในช่องค้นหา</li>
        <li>คลิกที่แถวใดก็ได้เพื่อดูรายละเอียดบัญชีนั้น</li>
    </ul>
    <x-guide-tip type="tip">
        บัญชีที่เปิดแล้วจะมีสถานะ <strong>"เปิดใช้งาน"</strong> (สีเขียว) ถ้าต้องการปิดบัญชีในอนาคต ให้ถอนเงินออกให้หมดก่อน แล้วเปลี่ยนสถานะเป็น "ปิดบัญชี"
    </x-guide-tip>
</div>

