<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        เมื่อมีเวอร์ชันใหม่ของแอป ระบบจะตรวจสอบและแจ้งให้ท่านทราบอัตโนมัติทุกครั้งที่เปิดแอป
        ควรอัพเดทเสมอเพื่อให้ได้ฟีเจอร์ใหม่ แก้ไขปัญหาต่างๆ และใช้งานได้ราบรื่น
    </p>

    <x-guide-tip type="info">
        การอัพเดทแอป <strong>ไม่ทำให้ข้อมูลหาย</strong> เพราะข้อมูลทั้งหมด (สินเชื่อ เงินฝาก หุ้น แจ้งเตือน)
        เก็บอยู่บนเซิร์ฟเวอร์ (คอมพิวเตอร์กลาง) ไม่ได้เก็บในแอป จึงอัพเดทได้อย่างสบายใจ
    </x-guide-tip>

    <x-guide-step :number="1" title="ระบบตรวจสอบอัตโนมัติ">
        <p>ทุกครั้งที่ท่านเปิดแอป ระบบจะตรวจสอบว่ามีเวอร์ชันใหม่หรือไม่</p>
        <p>ขั้นตอนนี้เกิดขึ้นอัตโนมัติ <strong>ไม่ต้องทำอะไร</strong></p>
        <p>ถ้าไม่มีเวอร์ชันใหม่ จะเข้าใช้งานตามปกติ</p>
        <p>ถ้ามีเวอร์ชันใหม่ จะแสดงกล่องแจ้งเตือนขึ้นมา</p>
    </x-guide-step>

    <x-guide-step :number="2" title="กล่องแจ้งเตือนอัพเดท">
        <p>เมื่อมีเวอร์ชันใหม่ จะมี <strong>กล่องข้อความ</strong> แสดงขึ้นมากลางหน้าจอ</p>
        <p>ข้อความจะบอกว่า:</p>
        <div class="bg-gray-800 rounded-lg p-4 my-3">
            <p class="text-white font-bold">"มีเวอร์ชันใหม่ v1.2.0 พร้อมให้อัพเดท"</p>
            <p class="text-gray-400 text-sm mt-1">(เลขเวอร์ชันอาจต่างจากนี้)</p>
        </div>
        <p>มีปุ่มให้เลือก 2 ปุ่ม:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li><strong>"อัพเดทเลย"</strong> - กดเพื่อเริ่มดาวน์โหลดและติดตั้งเวอร์ชันใหม่ทันที (แนะนำ)</li>
            <li><strong>"ภายหลัง"</strong> - กดเพื่อข้ามไปก่อน ใช้เวอร์ชันเก่าต่อ (ครั้งต่อไปจะถามอีก)</li>
        </ul>
        <x-guide-screenshot type="app" src="images/guide/mobile-app/update-dialog.png" alt="กล่องแจ้งอัพเดท" caption="กล่องแจ้งเตือนเมื่อมีเวอร์ชันใหม่" />
    </x-guide-step>

    <x-guide-step :number="3" title="กด 'อัพเดทเลย'">
        <p>เมื่อกดปุ่ม <strong>"อัพเดทเลย"</strong> ระบบจะเริ่มดาวน์โหลดไฟล์เวอร์ชันใหม่อัตโนมัติ</p>
        <p>จะเห็นแถบความคืบหน้าแสดงว่ากำลังดาวน์โหลด</p>
        <p>รอจนดาวน์โหลดเสร็จ (ใช้เวลาประมาณ 1-3 นาที ขึ้นอยู่กับความเร็วอินเทอร์เน็ต)</p>
        <p>ถ้าดาวน์โหลดช้า ตรวจสอบว่าเชื่อมต่อ Wi-Fi หรืออินเทอร์เน็ตมือถืออยู่</p>
    </x-guide-step>

    <x-guide-step :number="4" title="ติดตั้งอัพเดท">
        <p>เมื่อดาวน์โหลดเสร็จ จะแสดงหน้าจอติดตั้ง (เหมือนตอนติดตั้งครั้งแรก)</p>
        <p>กดปุ่ม <strong>"ติดตั้ง" (Install)</strong></p>
        <p>รอสักครู่ ประมาณ 30 วินาที ถึง 1 นาที</p>
        <p>มือถืออาจถามว่า "ต้องการติดตั้งอัพเดทนี้หรือไม่?" ให้กด <strong>"ติดตั้ง"</strong></p>
        <x-guide-screenshot type="app" src="images/guide/mobile-app/update-install.png" alt="ติดตั้งอัพเดท" caption="กดติดตั้งเพื่อติดตั้งเวอร์ชันใหม่" />
    </x-guide-step>

    <x-guide-step :number="5" title="เปิดแอปใหม่">
        <p>เมื่อติดตั้งเสร็จ กดปุ่ม <strong>"เปิด" (Open)</strong></p>
        <p>แอปจะเปิดขึ้นมาด้วยเวอร์ชันใหม่</p>
        <p>ท่านอาจต้องเข้าสู่ระบบใหม่ (กรอกอีเมลและรหัสผ่าน) ขึ้นอยู่กับเวอร์ชันที่อัพเดท</p>
        <p>ข้อมูลทั้งหมดยังอยู่ครบ ไม่มีอะไรหาย</p>
    </x-guide-step>

    <x-guide-step :number="6" title="ตรวจสอบเวอร์ชันปัจจุบัน">
        <p>ถ้าต้องการตรวจสอบว่าใช้แอปเวอร์ชันอะไรอยู่ ให้ทำดังนี้:</p>
        <ol class="list-decimal pl-5 space-y-2 mt-2">
            <li>กดแท็บ <strong>"อื่นๆ"</strong> ที่แถบด้านล่าง (ตัวสุดท้ายทางขวา)</li>
            <li>กดที่ <strong>"เกี่ยวกับ"</strong></li>
            <li>จะแสดงเลขเวอร์ชันปัจจุบัน เช่น "v1.2.0"</li>
        </ol>
        <x-guide-screenshot type="app" src="images/guide/mobile-app/about-version.png" alt="ตรวจสอบเวอร์ชัน" caption="ดูเวอร์ชันแอปที่เมนู อื่นๆ > เกี่ยวกับ" />
    </x-guide-step>

    <x-guide-tip type="tip">
        <strong>ควรอัพเดททุกครั้งที่มีแจ้งเตือน</strong> เพื่อรับฟีเจอร์ใหม่ แก้ไขปัญหาที่พบ
        และให้แอปทำงานได้ราบรื่น ถ้าใช้เวอร์ชันเก่ามากๆ อาจใช้งานไม่ได้
    </x-guide-tip>

    <x-guide-tip type="warning">
        ถ้าอัพเดทไม่สำเร็จ ลองทำตามนี้:
        <ul class="list-disc pl-5 mt-2 space-y-1">
            <li>ตรวจสอบว่าเชื่อมต่ออินเทอร์เน็ตอยู่</li>
            <li>ตรวจสอบว่ามือถือมีพื้นที่ว่างเพียงพอ</li>
            <li>ลบแอปเก่าแล้วติดตั้งใหม่ทั้งหมด (ข้อมูลไม่หาย เพราะเก็บบนเซิร์ฟเวอร์)</li>
            <li>ติดต่อเจ้าหน้าที่กองทุนเพื่อขอความช่วยเหลือ</li>
        </ul>
    </x-guide-tip>
</div>

