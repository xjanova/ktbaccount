        โดยไม่ต้องเปิดเมนูหลายขั้นตอน
    </p>

    <x-guide-tip type="info">
        ปุ่มลัดเหล่านี้เป็นทางลัดไปยังหน้าต่างๆ ที่ใช้งานบ่อย คลิกปุ่มเดียวก็ไปถึงหน้าที่ต้องการได้เลย
        ไม่ต้องเปิดเมนูซ้ายมือทีละขั้น
    </x-guide-tip>

    <x-guide-step :number="1" title="ปุ่มลัดบนหน้าหลัก">
        <p>ที่หน้าหลัก (Dashboard) จะมีปุ่มลัดอยู่ด้านบน ปุ่มหลักๆ มีดังนี้:</p>
        <x-guide-screenshot src="images/guide/dashboard/quick-actions-buttons.png" alt="ปุ่มลัดบนหน้าหลัก" caption="ปุ่มลัดสำหรับทำงานที่ใช้บ่อย" />
    </x-guide-step>

    <x-guide-step :number="2" title="ปุ่ม &quot;บันทึกรายรับ&quot;">
        <p>คลิกปุ่ม <strong>"บันทึกรายรับ"</strong> เพื่อไปยังหน้าบันทึกรายรับทันที</p>
        <p>ใช้เมื่อกองทุนได้รับเงินเข้า เช่น:</p>
        <ul class="list-disc list-inside space-y-1 my-2">
            <li>สมาชิกชำระค่าหุ้นรายเดือน</li>
            <li>สมาชิกฝากเงินออม</li>
            <li>ได้รับดอกเบี้ยจากธนาคาร</li>
            <li>ได้รับเงินสนับสนุนจากหน่วยงาน</li>
            <li>สมาชิกชำระค่าธรรมเนียม</li>
        </ul>
        <x-guide-tip type="tip">
            รายรับส่วนใหญ่ของกองทุนมาจาก "ดอกเบี้ยเงินกู้" ที่สมาชิกชำระ
            ถ้ารับชำระสินเชื่อ ให้ใช้ปุ่ม "รับชำระสินเชื่อ" แทน เพราะระบบจะคำนวณเงินต้น+ดอกเบี้ยให้อัตโนมัติ
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="3" title="ปุ่ม &quot;บันทึกรายจ่าย&quot;">
        <p>คลิกปุ่ม <strong>"บันทึกรายจ่าย"</strong> เพื่อไปยังหน้าบันทึกรายจ่ายทันที</p>
        <p>ใช้เมื่อกองทุนจ่ายเงินออก เช่น:</p>
        <ul class="list-disc list-inside space-y-1 my-2">
            <li>จ่ายค่าตอบแทนคณะกรรมการ</li>
            <li>จ่ายค่าเช่าสถานที่/อุปกรณ์สำนักงาน</li>
            <li>จ่ายค่าน้ำ ค่าไฟ ค่าอินเทอร์เน็ต</li>
            <li>จ่ายค่าเดินทางไปติดต่อราชการ</li>
            <li>จ่ายค่าอบรมสัมมนา</li>
        </ul>
    </x-guide-step>

    <x-guide-step :number="4" title="ปุ่ม &quot;รับชำระสินเชื่อ&quot;">
        <p>คลิกปุ่ม <strong>"รับชำระสินเชื่อ"</strong> เพื่อไปยังหน้ารับชำระสินเชื่อทันที</p>
        <p>ใช้เมื่อสมาชิกมาชำระเงินกู้คืนกองทุน ระบบจะช่วยคำนวณให้อัตโนมัติ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>เงินต้น:</strong> ส่วนที่ตัดจากเงินกู้</li>
            <li><strong>ดอกเบี้ย:</strong> ดอกเบี้ยที่ต้องชำระ</li>
            <li><strong>ยอดคงเหลือ:</strong> เงินกู้ที่ยังเหลือหลังชำระ</li>
        </ul>
        <x-guide-tip type="info">
            เมื่อรับชำระสินเชื่อ ระบบจะบันทึกรายรับให้อัตโนมัติ ไม่ต้องไปบันทึกรายรับแยกอีก
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="5" title="กล่องแจ้งเตือนสินเชื่อค้างชำระ">
        <p>ที่ด้านล่างของหน้าหลัก จะมี <strong>กล่องสีแดง</strong> แสดงรายการสินเชื่อที่เลยกำหนดชำระแล้ว
        ประกอบด้วย:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>ชื่อสมาชิก:</strong> ผู้กู้ที่ยังไม่ชำระ</li>
            <li><strong>จำนวนเงิน:</strong> ยอดเงินที่ต้องชำระ (เงินต้น + ดอกเบี้ย)</li>
            <li><strong>วันครบกำหนด:</strong> วันที่ต้องชำระ (ซึ่งผ่านมาแล้ว)</li>
            <li><strong>จำนวนวันที่เลยกำหนด:</strong> เลยกำหนดมาแล้วกี่วัน</li>
        </ul>
        <x-guide-screenshot src="images/guide/dashboard/quick-actions-overdue.png" alt="กล่องแจ้งเตือนสินเชื่อค้างชำระ" caption="กล่องสีแดงแสดงรายการสินเชื่อที่เลยกำหนดชำระ" />
        <x-guide-tip type="warning">
            ควรตรวจสอบรายการสินเชื่อค้างชำระ <strong>ทุกวัน</strong> ที่เข้าสู่ระบบ
            และติดตามทวงถามสมาชิกที่เลยกำหนดชำระโดยเร็ว
            เพื่อไม่ให้ยอดค้างชำระสะสมมากขึ้น
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="6" title="การ์ดสรุปยอด">
        <p>ที่ด้านบนของหน้าหลัก ยังมี <strong>การ์ดสรุปยอด</strong> แสดงตัวเลขสำคัญ:</p>
        <ul class="list-disc list-inside space-y-2 my-4">
            <li><strong>สมาชิกทั้งหมด:</strong> จำนวนสมาชิกกองทุน</li>
            <li><strong>สินเชื่อคงค้าง:</strong> ยอดเงินกู้ทั้งหมดที่ยังไม่ชำระ</li>
            <li><strong>เงินฝากรวม:</strong> ยอดเงินฝากของสมาชิกทั้งหมด</li>
            <li><strong>รายรับเดือนนี้:</strong> ยอดรวมรายรับในเดือนปัจจุบัน</li>
        </ul>
        <p>ตัวเลขเหล่านี้อัปเดตอัตโนมัติทุกครั้งที่เปิดหน้าหลัก</p>
    </x-guide-step>

    <x-guide-tip type="tip">
