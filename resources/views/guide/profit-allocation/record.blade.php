@section('guide-content')
<div class="prose prose-invert max-w-none">
    <p class="text-lg text-gray-300 mb-8">
        หลังจากที่ประชุมใหญ่มีมติจัดสรรกำไรแล้ว ให้บันทึกข้อมูลลงในระบบตามขั้นตอนด้านล่างนี้
        ระบบจะบันทึกบัญชีให้อัตโนมัติทั้งหมด
    </p>

    <x-guide-step :number="1" title="เข้าเมนู &quot;รายรับ-รายจ่าย&quot;">
        <p>คลิกที่เมนู <strong>"รายรับ-รายจ่าย"</strong> ในแถบด้านซ้ายมือ (อยู่ในหมวด "บัญชีการเงิน")</p>
        <p>ระบบจะแสดงหน้ารายรับ-รายจ่าย</p>
    </x-guide-step>

    <x-guide-step :number="2" title="เลือกชุดบัญชี">
        <p>ถ้ากองทุนมีหลายชุดบัญชี ให้เลือกชุดบัญชีที่ต้องการบันทึกการจัดสรรกำไร</p>
        <p>ถ้ามีชุดบัญชีเดียว ระบบจะเลือกให้อัตโนมัติ</p>
    </x-guide-step>

    <x-guide-step :number="3" title="คลิก &quot;บันทึกการจัดสรรกำไร&quot;">
        <p>ในหน้ารายรับ-รายจ่าย ให้มองหาเมนูหรือปุ่ม <strong>"บันทึกการจัดสรรกำไร"</strong></p>
        <p>คลิกที่ปุ่มนี้ ระบบจะเปิดหน้าจัดสรรกำไรขึ้นมา</p>
    </x-guide-step>

    <x-guide-step :number="4" title="คลิก &quot;+ สร้างบันทึกการจัดสรรกำไร&quot;">
        <p>คลิกปุ่ม <strong>"+ สร้างบันทึกการจัดสรรกำไร"</strong> ที่มุมขวาบน</p>
        <p>ระบบจะเปิดแบบฟอร์มบันทึกการจัดสรรกำไรขึ้นมา</p>
    </x-guide-step>

    <x-guide-step :number="5" title="เลือกปีบัญชี">
        <p>ในช่อง <strong>"ปีบัญชี"</strong> ให้เลือกปีที่ต้องการจัดสรรกำไร</p>
        <p>เช่น ถ้าต้องการจัดสรรกำไรของปี 2568 ให้เลือก <strong>2568</strong></p>
        <p>ปีบัญชีคือปีที่กองทุนทำมาหาได้กำไร ไม่ใช่ปีที่ทำการจัดสรร</p>
        <x-guide-tip type="info">
            ปกติจะจัดสรรกำไรของ <strong>ปีที่แล้ว</strong> เช่น ตอนนี้ปี 2569 ก็จัดสรรกำไรของปี 2568
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="6" title="ใส่จำนวนเงินรวมที่จัดสรร">
        <p>ในช่อง <strong>"จำนวนเงินรวม"</strong> ให้ใส่ตัวเลข <strong>กำไรสุทธิทั้งหมด</strong> ที่จะนำมาจัดสรร</p>
        <p>ตัวเลขนี้ดูได้จาก:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>เมนู <strong>"รายงาน"</strong> → <strong>"งบกำไรขาดทุน"</strong></li>
            <li>ดูที่บรรทัด <strong>"กำไรสุทธิ"</strong></li>
            <li>นำตัวเลขนั้นมาใส่ในช่องนี้</li>
        </ul>
        <p class="mt-2">เช่น กำไรสุทธิ 100,000 บาท ก็ใส่ <strong>100000</strong></p>
        <x-guide-tip type="tip">
            ถ้าจำตัวเลขกำไรสุทธิไม่ได้ ให้เปิดเมนู "รายงาน" ในอีกแท็บ เพื่อดูตัวเลขไปพร้อมกัน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="7" title="ใส่ร้อยละแต่ละหมวด">
        <p>กรอกร้อยละของแต่ละหมวดตามมติที่ประชุม:</p>

        <h4 class="text-white font-semibold mt-4 mb-2">หมวดที่ต้องกรอก</h4>
        <ul class="list-disc pl-5 space-y-3 mt-2">
            <li>
                <strong>เงินสำรอง/ประกันความเสี่ยง:</strong> ใส่ร้อยละ เช่น <strong>25</strong> (หมายถึง 25%)
            </li>
            <li>
                <strong>เงินสมทบกองทุน:</strong> ใส่ร้อยละ เช่น <strong>10</strong> (หมายถึง 10%)
            </li>
            <li>
                <strong>เงินเฉลี่ยคืนสมาชิก:</strong> ใส่ร้อยละ เช่น <strong>30</strong> (หมายถึง 30%)
            </li>
            <li>
                <strong>ทุนสาธารณประโยชน์:</strong> ใส่ร้อยละ เช่น <strong>15</strong> (หมายถึง 15%)
            </li>
            <li>
                <strong>ค่าตอบแทนคณะกรรมการ:</strong> ใส่ร้อยละ เช่น <strong>20</strong> (หมายถึง 20%)
            </li>
        </ul>

        <h4 class="text-white font-semibold mt-4 mb-2">ระบบคำนวณอัตโนมัติ</h4>
        <p>เมื่อใส่ร้อยละแต่ละหมวด ระบบจะ <strong>คำนวณจำนวนเงิน</strong> ของแต่ละหมวดให้อัตโนมัติ</p>
        <p>เช่น กำไร 100,000 บาท ใส่สำรอง 25% → ระบบแสดง <strong>25,000 บาท</strong></p>

        <h4 class="text-white font-semibold mt-4 mb-2">ผลรวมร้อยละ</h4>
        <p>ที่ด้านล่างจะแสดง <strong>ผลรวมร้อยละ</strong> ของทุกหมวดรวมกัน</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>ถ้าแสดง <strong class="text-green-400">100.00%</strong> สีเขียว = ถูกต้อง บันทึกได้</li>
            <li>ถ้าแสดง <strong class="text-red-400">ไม่ถึง 100%</strong> หรือ <strong class="text-red-400">เกิน 100%</strong> สีแดง = ต้องแก้ไข</li>
        </ul>

        <x-guide-tip type="warning">
            ถ้ารวมไม่ถึง 100% หรือเกิน 100% ระบบจะ <strong>แจ้งเตือนและไม่ให้บันทึก</strong> ต้องแก้ไขตัวเลขร้อยละให้รวมเป็น 100.00% พอดีก่อน
        </x-guide-tip>
    </x-guide-step>

    <x-guide-step :number="8" title="ใส่วันที่ประชุม">
        <p>ในช่อง <strong>"วันที่ประชุม"</strong> ให้เลือกวันที่ที่ประชุมใหญ่มีมติจัดสรรกำไร</p>
        <p>เช่น ถ้าประชุมวันที่ 15 กุมภาพันธ์ 2569 ก็เลือกวันนั้น</p>
        <p>วันที่นี้ <strong>ไม่ใช่วันที่บันทึกในระบบ</strong> แต่เป็นวันที่ประชุมจริง</p>
    </x-guide-step>

    <x-guide-step :number="9" title="ใส่มติที่ประชุม">
        <p>ในช่อง <strong>"มติที่ประชุม"</strong> ให้พิมพ์ข้อความสั้นๆ ระบุว่าเป็นมติอะไร</p>
        <p>ตัวอย่าง:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li><strong>"มติที่ประชุมใหญ่สามัญ ครั้งที่ 1/2569"</strong></li>
            <li><strong>"มติที่ประชุมใหญ่สามัญประจำปี 2569 เมื่อวันที่ 15 ก.พ. 2569"</strong></li>
        </ul>
        <p class="mt-2">ข้อความนี้จะถูกบันทึกไว้เป็นหลักฐานอ้างอิง</p>
    </x-guide-step>

    <x-guide-step :number="10" title="ตรวจสอบข้อมูลทั้งหมด">
        <p>ก่อนกดบันทึก ให้ตรวจสอบข้อมูลทุกช่องอีกครั้ง:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>ปีบัญชี - ถูกปีหรือไม่?</li>
            <li>จำนวนเงินรวม - ตรงกับกำไรสุทธิหรือไม่?</li>
            <li>ร้อยละแต่ละหมวด - ตรงกับมติที่ประชุมหรือไม่?</li>
            <li>ผลรวมร้อยละ - เท่ากับ 100.00% หรือไม่?</li>
            <li>จำนวนเงินแต่ละหมวด - ถูกต้องหรือไม่?</li>
            <li>วันที่ประชุม - ถูกวันหรือไม่?</li>
            <li>มติที่ประชุม - ครบถ้วนหรือไม่?</li>
        </ul>
    </x-guide-step>

    <x-guide-step :number="11" title="กดบันทึก">
        <p>ถ้าข้อมูลทั้งหมดถูกต้องแล้ว ให้คลิกปุ่ม <strong>"บันทึก"</strong></p>
        <p class="mt-2">เมื่อบันทึกสำเร็จ ระบบจะทำสิ่งต่อไปนี้ <strong>อัตโนมัติ</strong>:</p>
        <ul class="list-disc pl-5 space-y-2 mt-2">
            <li>&#10003; <strong>หักเงินจากกำไรสะสม</strong> (บัญชี 33010)</li>
            <li>&#10003; <strong>แยกเข้าแต่ละหมวด</strong> ตามร้อยละที่กำหนด</li>
            <li>&#10003; <strong>บันทึกรายการบัญชี</strong> (สมุดรายวัน) ให้อัตโนมัติ</li>
            <li>&#10003; <strong>แสดงข้อความ "บันทึกสำเร็จ"</strong> สีเขียว</li>
        </ul>

        <x-guide-tip type="important">
            ตรวจสอบตัวเลขให้ถูกต้องก่อนบันทึก เพราะการจัดสรรกำไร <strong>มีผลกระทบต่องบการเงิน</strong> ทั้งหมดของกองทุน ถ้าบันทึกผิดจะต้องแก้ไขภายหลัง ซึ่งยุ่งยาก
        </x-guide-tip>
    </x-guide-step>

    <h3 class="text-xl font-bold text-white mt-10 mb-4">หลังบันทึกแล้ว</h3>
    <p>เมื่อบันทึกจัดสรรกำไรเสร็จแล้ว สามารถ:</p>
    <ul class="list-disc pl-5 space-y-2 mt-2">
        <li>กลับไปดูรายการที่บันทึกได้ที่หน้า "บันทึกการจัดสรรกำไร"</li>
        <li>ตรวจสอบผลในงบดุลว่ากำไรสะสมลดลงถูกต้อง</li>
        <li>ตรวจสอบว่าแต่ละหมวดได้รับเงินตามที่จัดสรร</li>
    </ul>

    <x-guide-tip type="tip">
        ถ้าต้องการ <strong>พิมพ์รายงานการจัดสรรกำไร</strong> เพื่อเก็บเป็นเอกสาร สามารถดาวน์โหลด PDF ได้จากหน้ารายละเอียดการจัดสรร
    </x-guide-tip>
</div>

